import fs from 'node:fs';
import assert from 'node:assert/strict';
import {parseHTML} from 'linkedom';
const root=new URL('../',import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),'utf8');
const data=JSON.parse(read('content/knowledge/founder-letter.json'));
const {document}=parseHTML(read('site/guides/be-the-one-they-follow/index.html'));
const paragraphs=[...document.querySelectorAll('.letter-section>p')].map(p=>p.textContent);
assert.deepEqual(paragraphs,data.sections.flatMap(s=>s.paragraphs),'Every final v3 paragraph is published in order');
assert.equal(document.querySelectorAll('h1').length,1);
assert(!document.body.textContent.includes('INTERNAL REP INFORMATION'));
assert(!document.body.textContent.includes('editorial review'));
assert.deepEqual([...document.querySelectorAll('.rep-opportunity>p:not(.eyebrow)')].map(p=>p.textContent),data.sidebar.split('\n\n'));
assert(document.querySelector('.founder-next a').href===data.ctaUrl);
for(const source of data.sourceReferences.flatMap(g=>g.sources))assert([...document.querySelectorAll('#article-sources a')].some(a=>a.getAttribute('href')===source.url),source.url);
const structured=JSON.parse(document.querySelector('script[type="application/ld+json"]').textContent);
assert.equal(structured.author.name,'Craig Stratton');assert.equal(structured.datePublished,'2026-10-04');
const home=parseHTML(read('site/index.html')).document;
assert(home.querySelector('.founder-feature a').href==='/guides/be-the-one-they-follow/');
assert([...home.querySelectorAll('[data-search-item]')].some(n=>n.textContent.includes('Be the one they follow')));
assert(read('site/feed.xml').includes('https://news.prospershield.io/guides/be-the-one-they-follow/'));
assert(read('site/sitemap.xml').includes('https://news.prospershield.io/guides/be-the-one-they-follow/'));
console.log(JSON.stringify({passed:true,paragraphs:paragraphs.length,sourceLinks:data.sourceReferences.flatMap(g=>g.sources).length,sidebarExact:true,homepageFeature:true,searchIndexed:true,rss:true,sitemap:true}));
